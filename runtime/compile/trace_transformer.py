def find_instruction_count_in_workdir(workdir: Path) -> int:
    if not workdir.exists():
        return None
    best = 0
    for p in workdir.rglob("*"):
        if p.is_file() and p.suffix in (".log", ".txt", ".stderr", ".stdout", ""):
            try:
                text = p.read_text(errors="ignore")
            except Exception:
                continue
            for pat in [
                r"Instructions generated by compiler\s+([\d,]+)",
                r"Number of instructions \(([\d,]+)\)",
                r"Compiler generated too many instructions \(([\d,]+)\)",
                r"total instructions\s*[:=]\s*([\d,]+)",
            ]:
                for m in re.finditer(pat, text):
                    n = int(m.group(1).replace(",", ""))
                    if n > best:
                        best = n
    return best or None


def main() -> int:
    return _run_full_trace()


def _run_full_trace() -> int:
    assert_neuron_available()
    cfg = CompileConfig(resolution=512, max_sequence_length=512, vae_mode="cpu_fp32")
    setup(cfg, timeout_min=45)
    probe_cache = ROOT / COMPILED_MODELS_DIR / "cache_512"
    probe_cache.mkdir(parents=True, exist_ok=True)
    os.environ["NEURON_COMPILE_CACHE_URL"] = str(probe_cache)
    os.environ["NEURON_CC_FLAGS"] = (
        "--model-type transformer --optlevel=1 "
        "--enable-fast-loading-neuron-binaries "
        "--auto-cast matmult --retry_failed_compilation"
    )

    import gc as _gc
    import json as _json
    from pathlib import Path as _Path

    import torch
    import torch_neuronx
    from safetensors.torch import load_file
    from zimage.transformer import ZImageTransformer2DModel

    from config import (
        DEFAULT_TRANSFORMER_CAP_FEAT_DIM,
        DEFAULT_TRANSFORMER_DIM,
        DEFAULT_TRANSFORMER_F_PATCH_SIZE,
        DEFAULT_TRANSFORMER_IN_CHANNELS,
        DEFAULT_TRANSFORMER_N_HEADS,
        DEFAULT_TRANSFORMER_N_KV_HEADS,
        DEFAULT_TRANSFORMER_N_LAYERS,
        DEFAULT_TRANSFORMER_N_REFINER_LAYERS,
        DEFAULT_TRANSFORMER_NORM_EPS,
        DEFAULT_TRANSFORMER_PATCH_SIZE,
        DEFAULT_TRANSFORMER_QK_NORM,
        DEFAULT_TRANSFORMER_T_SCALE,
        ROPE_AXES_DIMS,
        ROPE_AXES_LENS,
        ROPE_THETA,
    )
    from neuron.runtime import FixedShapeTransformerWrapper, apply_patches
    from utils import ensure_model_weights

    apply_patches(attention_backend="native")
    model_path = _Path(ensure_model_weights(MODEL_PATH, verify=False))
    d = model_path / "transformer"
    with open(d / "config.json") as f:
        xcfg = _json.load(f)
    with torch.device("meta"):
        transformer = ZImageTransformer2DModel(
            all_patch_size=tuple(xcfg.get("all_patch_size", DEFAULT_TRANSFORMER_PATCH_SIZE)),
            all_f_patch_size=tuple(xcfg.get("all_f_patch_size", DEFAULT_TRANSFORMER_F_PATCH_SIZE)),
            in_channels=xcfg.get("in_channels", DEFAULT_TRANSFORMER_IN_CHANNELS),
            dim=xcfg.get("dim", DEFAULT_TRANSFORMER_DIM),
            n_layers=xcfg.get("n_layers", DEFAULT_TRANSFORMER_N_LAYERS),
            n_refiner_layers=xcfg.get("n_refiner_layers", DEFAULT_TRANSFORMER_N_REFINER_LAYERS),
            n_heads=xcfg.get("n_heads", DEFAULT_TRANSFORMER_N_HEADS),
            n_kv_heads=xcfg.get("n_kv_heads", DEFAULT_TRANSFORMER_N_KV_HEADS),
            norm_eps=xcfg.get("norm_eps", DEFAULT_TRANSFORMER_NORM_EPS),
            qk_norm=xcfg.get("qk_norm", DEFAULT_TRANSFORMER_QK_NORM),
            cap_feat_dim=xcfg.get("cap_feat_dim", DEFAULT_TRANSFORMER_CAP_FEAT_DIM),
            rope_theta=xcfg.get("rope_theta", ROPE_THETA),
            t_scale=xcfg.get("t_scale", DEFAULT_TRANSFORMER_T_SCALE),
            axes_dims=xcfg.get("axes_dims", ROPE_AXES_DIMS),
            axes_lens=xcfg.get("axes_lens", ROPE_AXES_LENS),
        ).to(torch.bfloat16)
    with open(d / "diffusion_pytorch_model.safetensors.index.json") as f:
        idx = _json.load(f)
    sd = {}
    for sf in sorted(set(idx["weight_map"].values())):
        sd.update(load_file(str(d / sf), device="cpu"))
    sd = {k: v.to(torch.bfloat16) for k, v in sd.items()}
    transformer.load_state_dict(sd, strict=False, assign=True)
    del sd
    _gc.collect()
    transformer.eval()

    wrapper = FixedShapeTransformerWrapper(transformer).to(torch.bfloat16).eval()

    lat_example = torch.randn(16, 1, 64, 64, dtype=torch.bfloat16) * 0.1
    t_example = torch.tensor([0.5], dtype=torch.bfloat16)
    cap_example = torch.randn(512, 2560, dtype=torch.bfloat16) * 0.01

    logger.info("\n[[transformer] === Single-NEFF full transformer trace at 512×512 ===")
    logger.info(f" lat : {lat_example.shape} {lat_example.dtype}")
    logger.info(f" t   : {t_example.shape}   {t_example.dtype}")
    logger.info(f" cap : {cap_example.shape} {cap_example.dtype}")

    logger.info("\n[[transformer] CPU reference forward (may take ~60s) …")
    t0 = time.perf_counter()
    try:
        with torch.no_grad():
            cpu_out = wrapper(lat_example, t_example, cap_example)
        cpu_max = float(cpu_out.abs().max())
        cpu_time = time.perf_counter() - t0
        logger.info(f"[transformer] CPU out abs_max={cpu_max:.4f}  time={cpu_time:.1f}s")
    except Exception as e:
        logger.error(f"[transformer] CPU forward failed (not fatal): {e}")
        cpu_out = None
        cpu_max = None

    logger.info("\n[[transformer] torch_neuronx.trace (compile can take 10-30 min) …")
    WORKDIR.mkdir(parents=True, exist_ok=True)
    t0 = time.perf_counter()
    inst_count = None
    try:
        traced = torch_neuronx.trace(
            wrapper,
            (lat_example, t_example, cap_example),
            compiler_workdir=str(WORKDIR),
            compiler_args=["--model-type=transformer", "--optlevel=1", "--auto-cast", "matmult"],
        )
        trace_time = time.perf_counter() - t0
        torch.jit.save(traced, str(ARTIFACT_PT))
        size = ARTIFACT_PT.stat().st_size
        logger.info(
            f"[transformer] trace completed in {trace_time:.1f}s; saved {size / (1024 * 1024):.1f} MB"
        )
    except Exception as e:
        trace_time = time.perf_counter() - t0
        traceback.print_exc()
        inst_count = find_instruction_count_in_workdir(WORKDIR)
        result = {
            "experiment": "transformer",
            "description": "Single-NEFF full transformer trace at 512x512",
            "status": "trace_failed",
            "trace_time_s": round(trace_time, 1),
            "error": str(e)[:500],
            "instructions": inst_count,
            "v6_L3_insts_1024": 8_528_784,
            "passed": False,
        }
        save_results(result, RESULTS_PATH)
        return 1

    logger.info("\n[[transformer] Compare traced output to CPU …")
    try:
        with torch.no_grad():
            traced_out = traced(lat_example, t_example, cap_example)
        traced_max = float(traced_out.abs().max())
        max_err = (
            float((cpu_out.float() - traced_out.float()).abs().max())
            if cpu_out is not None
            else None
        )
        logger.info(f"[transformer]   traced out abs_max={traced_max:.4f}  max_err={max_err}")
    except Exception as e:
        logger.error(f"transformer   traced forward failed: {e}")
        traced_max = 0.0
        max_err = float("inf")

    if traced_max > 0.01:
        times = []
        for i in range(3):
            t0 = time.perf_counter()
            with torch.no_grad():
                _ = traced(lat_example, t_example, cap_example)
            dt = time.perf_counter() - t0
            times.append(dt)
        logger.info(f"[transformer] single-NEFF forward times: {[round(t, 3) for t in times]}s")
    else:
        times = []

    inst_count = find_instruction_count_in_workdir(WORKDIR)

    result = {
        "experiment": "transformer",
        "description": "Single-NEFF full transformer trace at 512x512",
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S UTC", time.gmtime()),
        "status": "ok" if traced_max > 0.01 else "output_all_zeros",
        "trace_time_s": round(trace_time, 1),
        "neff_size_mb": round(ARTIFACT_PT.stat().st_size / (1024 * 1024), 1),
        "instructions": inst_count,
        "cap_status": (
            None if inst_count is None else ("under_5M" if inst_count < 5_000_000 else "over_5M")
        ),
        "cpu_abs_max": cpu_max,
        "traced_abs_max": traced_max,
        "max_err_vs_cpu": max_err,
        "fwd_times_s": [round(t, 3) for t in times],
        "v6_L3_insts_1024": 8_528_784,
        "v6_L3_verdict_1024": "FAIL (over 5M cap)",
        "passed": traced_max > 0.01 and (inst_count is None or inst_count < 5_000_000),
        "artifact_path": str(ARTIFACT_PT),
    }
    save_results(result, RESULTS_PATH)
    logger.info(
        f"\n[[transformer] {'OK:' if result['passed'] else 'ERROR:'} done. "
        f"instructions={inst_count}  traced_max={traced_max}"
    )
    return 0 if result["passed"] else 1


if __name__ == "__main__":
    try:
        sys.exit(main())
    except TimeoutError as e:
        logger.error(f"transformer TIMEOUT: {e}")
        sys.exit(124)
    except Exception:
        traceback.print_exc()
        sys.exit(1)
